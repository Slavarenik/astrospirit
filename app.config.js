const fs = require("fs");
const path = require("path");
const appJson = require("./app.json");

/** Load the project's .env into process.env when Expo CLI hasn't already. */
function loadDotEnv() {
  const envPath = path.join(__dirname, ".env");
  if (!fs.existsSync(envPath)) return;
  for (const line of fs.readFileSync(envPath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq < 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

loadDotEnv();

const env = (key) => (process.env[key] ?? "").trim();

const googleTranslateApiKey = env("EXPO_PUBLIC_GOOGLE_TRANSLATE_API_KEY");

/** Write the key into a TS module so Metro always bundles it (more reliable than
 *  process.env inlining / Constants.extra in Expo Go). DEV CONVENIENCE ONLY —
 *  once the `translateProxy` Cloud Function is deployed (see functions/) and
 *  Firebase config below is filled in, the app calls that instead and this
 *  key stops being shipped to the client at all. See functions/README.md. */
const translateEnvPath = path.join(__dirname, "src/shared/i18n/translateEnv.ts");
fs.writeFileSync(
  translateEnvPath,
  [
    "/** Auto-generated by app.config.js from .env — do not edit by hand. */",
    `export const GOOGLE_TRANSLATE_API_KEY = ${JSON.stringify(googleTranslateApiKey)};`,
    "",
  ].join("\n")
);

/** Firebase web config — all public/client-safe identifiers (not secrets).
 *  Fill these in from Firebase Console → Project settings → Your apps → Web
 *  app → SDK setup and configuration → Config. Leave any blank until you've
 *  created the project; `isFirebaseConfigured()` gates every Firebase call
 *  so the app runs fine (friends/auth screens just show a "not set up yet"
 *  state) before you do. */
const firebaseConfig = {
  apiKey: env("EXPO_PUBLIC_FIREBASE_API_KEY"),
  authDomain: env("EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN"),
  projectId: env("EXPO_PUBLIC_FIREBASE_PROJECT_ID"),
  storageBucket: env("EXPO_PUBLIC_FIREBASE_STORAGE_BUCKET"),
  messagingSenderId: env("EXPO_PUBLIC_FIREBASE_MESSAGING_SENDER_ID"),
  appId: env("EXPO_PUBLIC_FIREBASE_APP_ID"),
};

/** The OAuth 2.0 "Web client" Firebase auto-creates once you enable the
 *  Google sign-in provider — NOT the iOS client id from GoogleService-Info.plist.
 *  Find it in Firebase Console → Authentication → Sign-in method → Google →
 *  "Web SDK configuration" → Web client ID. Required so the ID token
 *  @react-native-google-signin/google-signin returns has the audience
 *  Firebase Auth expects. */
const googleWebClientId = env("EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID");

/** RevenueCat public SDK keys — RevenueCat dashboard → Project settings →
 *  API keys. Public, client-safe (same note as Firebase above). Required
 *  for real StoreKit / Play Billing purchases; without them the Paywall
 *  shows an unavailable state (no local premium unlock). */
const revenueCatConfig = {
  iosApiKey: env("EXPO_PUBLIC_REVENUECAT_IOS_API_KEY"),
  androidApiKey: env("EXPO_PUBLIC_REVENUECAT_ANDROID_API_KEY"),
};

/** Expo config — injects Google Translate API key + Firebase config + RevenueCat config from env / .env. */
module.exports = {
  expo: {
    ...appJson.expo,
    extra: {
      ...appJson.expo.extra,
      googleTranslateApiKey,
      firebase: firebaseConfig,
      googleWebClientId,
      revenueCat: revenueCatConfig,
    },
  },
};
